"""fwg-gen: regenerate committed artifacts from the ontology. ``--check`` fails on drift (CI).

Besides the package's ``generated/`` files it writes the Claude Code skill of the plugin
(``plugin/skills/workgraph/SKILL.md``) when run from a source checkout that has ``plugin/``.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

from florque_graph_core.generate import render_card, render_constraints, render_integrity

from florque_workgraph_domain import GENERATED_DIR, PACKAGE_DIR, load

SKILL_SOURCE = PACKAGE_DIR / "SKILL.md"


def render_skill(guide: str, card: str) -> str:
    """The plugin's workgraph skill: the hand-written domain guide plus the generated card."""
    body = card.split("\n", 1)[1] if card.startswith("# ") else card
    return (
        guide.rstrip("\n")
        + "\n\n<!-- Below: generated by fwg-gen from the ontology; do not edit. -->\n\n"
        + "## Ontology card (base schema)\n\n"
        + "Tenants and projects may add classes through extensions; "
        + "`fwg describe -p PROJECT_ID` prints the card that applies.\n\n"
        + re.sub(r"(?m)^(#+) ", r"#\1 ", body.lstrip("\n"))
    )


def _plugin_skill() -> Path | None:
    for parent in GENERATED_DIR.parents:
        plugin = parent / "plugin"
        if (plugin / ".claude-plugin" / "plugin.json").is_file():
            return plugin / "skills" / "workgraph" / "SKILL.md"
    return None


def artifacts() -> dict[Path, str]:
    model = load()
    card = render_card(model)
    out = {
        GENERATED_DIR / "card.md": card,
        GENERATED_DIR / "constraints.cypher": render_constraints(model),
        GENERATED_DIR / "integrity_checks.cypher": render_integrity(model),
    }
    skill = _plugin_skill()
    if skill is not None:
        out[skill] = render_skill(SKILL_SOURCE.read_text(), card)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="fwg-gen", description=__doc__)
    ap.add_argument(
        "--check", action="store_true", help="exit 1 if generated files are out of date"
    )
    args = ap.parse_args(argv)
    drift = []
    for path, content in artifacts().items():
        current = path.read_text() if path.exists() else None
        if current != content:
            drift.append(path.name)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    if args.check and drift:
        print(f"Generated artifacts out of date: {', '.join(drift)}. Run fwg-gen.", file=sys.stderr)
        return 1
    print("up to date" if not drift else f"wrote {', '.join(drift)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
